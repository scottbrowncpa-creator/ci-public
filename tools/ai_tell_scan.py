# -*- coding: utf-8 -*-
"""Scan output/ workbooks and Word docs for AI-writing tells.

Checklist source: memory ai-writing-tells-checklist + workpaper-style-not-ai.
Read-only. Writes a CSV of every hit so the fixer and a human can work from it.

    python tools/ai_tell_scan.py [root] [--csv out.csv]
"""
import sys, os, re, csv, zipfile, argparse

PATTERNS = [
    # (tag, regex, mechanical)   mechanical = safe to fix by rule
    ("em-dash",      r"[—–]", True),
    ("double-hyphen", r"(?<![-\w])--(?![-\w])", True),
    ("curly-quote",  r"[‘’“”]", True),
    ("ellipsis-char", r"…", True),
    ("arrow",        r"[→←⇒]", True),
    ("VERIFY-caps",  r"\bVERIFY\b", False),
    ("first-person", r"\b(I|I'm|I've|I'd|we|we're|we've|our|us|my|me)\b", False),
    ("ai-vocab",     r"\b(additionally|align(s|ed)? with|boasts?|bolster(ed|s)?|crucial|delve|emphasi[sz]ing|enhanc(e|ed|es|ing)|foster(ing)?(?! (care|home|parent|famil))|garner|highlight(s|ed|ing)?|interplay|intricate|landscape|meticulous(ly)?|pivotal|robust|showcas(e|es|ing)|tapestry|testament|underscor(e|es|ed|ing)|vibrant|seamless(ly)?|leverag(e|es|ed|ing)|streamlin(e|ed|es|ing)|comprehensive|ensur(e|es|ed|ing) that|utiliz(e|es|ed|ing)|foundational|realm(?! (id\b|\d)))\b", False),
    ("copula-dodge", r"\b(serves as|stands as|functions as|acts as|operates as)\b", False),
    ("filler",       r"\b(it is important to note|it's important to note|worth noting|note that|in order to|as a result of|the fact that|in summary|in conclusion|overall,|essentially|in other words)\b", False),
    ("not-x-but-y",  r"\bnot (just |only |merely )?[\w$,.\- ]{1,40}?(, but| - but| but rather|; it)\b|\bnot only\b", False),
    ("chatbot",      r"\b(let me know|happy to|I hope|feel free|here is|here's a|would you like)\b", False),
    # WARN only: each has a real use, so a human decides.
    ("heres-the-thing", r"\bhere['\u2019]?s the thing\b", False),
    ("careful-consideration", r"\bafter careful consideration\b", False),
    ("quick-update", r"\bquick update\b", False),
    ("most-people", r"\bmost people\b", False),
    ("adverb-quietly", r"\bquietly\b", False),
    # "This isn't a X. It's a Y." / "This is not a X, it is a Y": two short sentences, the grand pronouncement.
    ("pronouncement", r"\b(this|that|it|these|those|they)\s+(isn['\u2019]?t|is not|aren['\u2019]?t|are not|wasn['\u2019]?t|was not)\s+(just\s+|only\s+|merely\s+)?(an?\s+|the\s+)?[^.!?;\n]{1,40}[.,;]\s*(it['\u2019]?s|it is|this is|that['\u2019]?s|that is|they['\u2019]?re|they are)\b", False),
    ("markdown",     r"\*\*|```|^#{1,3} ", False),
    ("process-talk", r"\b(the model|this workbook (was|is) (built|generated|designed)|generated by|the script|the generator|by rule|per the playbook|year-end playbook|Claude)\b", False),
    # Cells like "not read", "not extracted", "read before step 2", "OCR'd",
    # "text layer" read like a worker's notes to itself. State the fact or mark it open: "Reserve terms in Indenture; open."
    ("work-notes",   r"\b(not (yet )?(read|extracted|parsed)|read before step|read sec(tion)? \d|this pass|OCR('?d)?|text layer|image[- ]only( PDF)?|scan capped|dumps?)\b", False),
]
RX = [(t, re.compile(p, re.I if t not in ("VERIFY-caps", "first-person") else 0), m) for t, p, m in PATTERNS]
LONG_WORDS = 40
# Fund and program names are not first person ('Title I-A').
# Label + Roman numeral I (same list as wb_lint.ROMAN_I), I-A / I-C style suffixes, and P&I, I/O abbreviations are stripped first.
ROMAN_I = re.compile(r"\b(Title|Part|Type|Class|Phase|Schedule|Tier|Article|Section|Chapter|Level|Appendix|Exhibit|Form|Grade|Round|Series|Step|Stage|Category)\s+I\b")
NOT_PRONOUN_I = re.compile(r"(?<![A-Za-z])I(?=-[A-Z0-9])|(?<=[&/])I\b|\bI(?=[&/])")


def _strip_numeral_i(text):
    return NOT_PRONOUN_I.sub("x", ROMAN_I.sub(r"\1 x", text))


def hits_in(text):
    out = []
    for tag, rx, mech in RX:
        if rx.search(_strip_numeral_i(text) if tag == "first-person" else text):
            out.append(tag)
    if len(text.split()) > LONG_WORDS:
        out.append("over-40-words")
    return out


def scan_xlsx(path):
    import openpyxl
    try:
        wb = openpyxl.load_workbook(path, read_only=True)
    except Exception as e:
        yield ("?", "?", f"OPEN FAILED {e}", ["open-failed"]); return
    for ws in wb.worksheets:
        yield (ws.title, "TAB", ws.title, hits_in(ws.title) if len(ws.title) > 3 else [])
        try:
            for row in ws.iter_rows():
                for c in row:
                    v = getattr(c, "value", None)
                    if isinstance(v, str) and not v.startswith("=") and len(v) > 3:
                        h = hits_in(v)
                        if h:
                            yield (ws.title, c.coordinate, v, h)
        except Exception as e:
            yield (ws.title, "?", f"READ FAILED {e}", ["read-failed"])
    wb.close()


def scan_docx(path):
    import docx
    try:
        d = docx.Document(path)
    except Exception as e:
        yield ("?", "?", f"OPEN FAILED {e}", ["open-failed"]); return
    for i, p in enumerate(d.paragraphs):
        if p.text.strip():
            h = hits_in(p.text)
            if h: yield ("body", f"p{i}", p.text, h)
    for ti, t in enumerate(d.tables):
        for ri, r in enumerate(t.rows):
            for ci, c in enumerate(r.cells):
                h = hits_in(c.text) if c.text.strip() else []
                if h: yield ("table", f"t{ti}r{ri}c{ci}", c.text, h)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root", nargs="?", default=os.path.join(os.path.dirname(__file__), "..", "output"))
    ap.add_argument("--csv", default=None)
    a = ap.parse_args()
    root = os.path.abspath(a.root)
    rows = []
    nfiles = 0
    for dp, dn, fn in os.walk(root):
        for f in fn:
            if f.startswith("~$"): continue
            p = os.path.join(dp, f)
            ext = f.lower().rsplit(".", 1)[-1]
            if ext == "xlsx": gen = scan_xlsx(p)
            elif ext == "docx": gen = scan_docx(p)
            else: continue
            nfiles += 1
            for sheet, ref, text, tags in gen:
                if tags:
                    rows.append((os.path.relpath(p, root), sheet, ref, "|".join(tags), text.replace("\n", " / ")[:500]))
    out = a.csv or os.path.join(root, "..", "scratch", "ai_tell_scan.csv")
    with open(out, "w", encoding="utf-8-sig", newline="") as fh:
        w = csv.writer(fh); w.writerow(["file", "sheet", "ref", "tags", "text"]); w.writerows(rows)
    from collections import Counter
    tc = Counter(t for r in rows for t in r[3].split("|"))
    fc = Counter(r[0] for r in rows)
    print(f"files scanned {nfiles} | files with hits {len(fc)} | hits {len(rows)}")
    for t, n in tc.most_common(): print(f"  {t:<15} {n}")
    print("csv:", os.path.abspath(out))


if __name__ == "__main__":
    main()
