# -*- coding: utf-8 -*-
"""Clean up file metadata on docx/xlsx/pptx before they go out: placeholder authors left by code libraries, missing Office app tag, batch timestamps, build notes and git hashes in the text, one template across a set.

    python tools/doc_fingerprint.py check  f1.docx [f2.xlsx ...]            exit 0 clean, 1 hits, 2 usage
    python tools/doc_fingerprint.py fix    f1.docx [...] --author "Pat Lee" [--company "Example Co."]
                                           [--created "2026-10-24 09:10"] [--spread-minutes 25] [--no-text]

Why: a file saved by a code library shows the library as its author, and build notes left in a change log mean nothing to the reader. The person who owns the file should be on it.

check  reports per file: creator / lastModifiedBy from a library, description "generated by", no <Application> or one that
       is not Office, revision 1, created == modified, template dates (2013). Text: git hashes after release/commit/build,
       "phase C" build talk, "SOP set build", pipeline/agent/Claude/generated, "I didn't guess", bullets ending "(Name)".
       Set: 3+ files created inside 60 seconds; 3+ files sharing the same heading skeleton. Writes nothing.
fix    rewrites docProps/core.xml and app.xml in place (author, company, Office application tag, revision 2, modified = now),
       rewrites the text tells it can (hash lines become "as of <date>", "phase C" becomes "draft 3"), backs up to
       scratch/fingerprint/backup/ first, and prints every change. --created / --spread-minutes change the created stamp
       only when asked; default leaves it. Opening and saving each file in Word also clears the stamps and the window.
Works on the zip, so docx-js, python-docx, openpyxl and python-pptx output all count. stamp_author() is the one-call
version for generator scripts.
"""
import argparse
import datetime as dt
import os
import re
import shutil
import sys
import zipfile
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
BACKUP = Path(os.environ.get("DOC_FINGERPRINT_BACKUP") or ROOT / "scratch" / "fingerprint" / "backup")
KINDS = {".docx": "word", ".docm": "word", ".xlsx": "sheet", ".xlsm": "sheet", ".pptx": "slides"}
APP_NAME = {"word": "Microsoft Office Word", "sheet": "Microsoft Excel", "slides": "Microsoft Office PowerPoint"}
LIB_NAMES = {"", "un-named", "unnamed", "python-docx", "openpyxl", "python-pptx", "docx", "steve canny", "author",
             "user", "unknown", "claude", "anthropic", "generator", "script"}
WINDOW_SECONDS = 60
SET_MIN = 3

CORE_NS = {
    "cp": "http://schemas.openxmlformats.org/package/2006/metadata/core-properties",
    "dc": "http://purl.org/dc/elements/1.1/",
    "dcterms": "http://purl.org/dc/terms/",
    "dcmitype": "http://purl.org/dc/dcmitype/",
    "xsi": "http://www.w3.org/2001/XMLSchema-instance",
}
APP_NS = "http://schemas.openxmlformats.org/officeDocument/2006/extended-properties"
VT_NS = "http://schemas.openxmlformats.org/officeDocument/2006/docPropsVTypes"

# a git short (7-10) or full (40) hash with at least one letter and one digit, so 2026102 and deadbeef alone do not count.
# 11-39 hex is not a git hash here (mail message keys are often 12 hex).
HASH = r"\b(?=[0-9a-f]*[a-f])(?=[0-9a-f]*\d)(?:[0-9a-f]{7,10}|[0-9a-f]{40})\b"
TEXT_TELLS = [
    ("git-hash", re.compile(r"\b(release|commit|build|rev(?:ision)?|version|sha)\s+" + HASH, re.I)),
    # "phase C" is a tell only next to build talk or on a dated change-log line; "phase A in June" on a roof job is not
    ("build-phase", re.compile(r"\b(set build|build|pipeline|run|pass|batch|sweep|generation),?\s+phase\s+([A-Z]|\d{1,2})\b", re.I)),
    ("build-phase", re.compile(r"^\s*\d{1,2}/\d{1,2}(/\d{2,4})?\b[^.]*\bphase\s+[A-H]\b", re.I)),
    ("pipeline-talk", re.compile(r"\b(SOP set build|agent pipeline|generated (by|using|with)|auto-?generated|python-docx|openpyxl|docx-js|"
                                 r"the (script|generator|pipeline|model)|Claude|LLM|assistant)\b", re.I)),
    ("didnt-guess", re.compile(r"\bI (didn'?t|did not|won'?t|will not) (guess|invent|assume|make (that|this|anything) up)\b", re.I)),
    ("ai-chat", re.compile(r"\b(let me know|happy to|feel free|I hope this)\b", re.I)),
]
ATTRIB_RX = re.compile(r"\(([A-Z][a-z]+(?: [A-Z][a-z]+)?)\)\s*\.?\s*$")
# common template headings; a set that shares 4+ of these in the same order came from one template
SKELETON_WORDS = ("purpose", "scope", "who does what", "common misses", "open questions", "change log", "appendix")


def kind_of(path):
    return KINDS.get(Path(path).suffix.lower())


def read_part(z, name):
    try:
        return z.read(name).decode("utf-8", errors="replace")
    except KeyError:
        return None


def _tag(xml, tag):
    m = re.search(r"<%s(?:\s[^>]*)?>(.*?)</%s>" % (re.escape(tag), re.escape(tag)), xml or "", re.S)
    if m:
        return re.sub(r"<[^>]+>", "", m.group(1)).strip()
    if re.search(r"<%s(?:\s[^>]*)?/>" % re.escape(tag), xml or ""):
        return ""
    return None


def _parse_time(s):
    if not s:
        return None
    s = s.strip().replace("Z", "+00:00")
    for fmt in ("%Y-%m-%dT%H:%M:%S%z", "%Y-%m-%dT%H:%M:%S.%f%z", "%Y-%m-%dT%H:%M%z", "%Y-%m-%d%z"):
        try:
            return dt.datetime.strptime(s, fmt)
        except ValueError:
            pass
    try:
        t = dt.datetime.fromisoformat(s)
        return t if t.tzinfo else t.replace(tzinfo=dt.timezone.utc)
    except ValueError:
        return None


def metadata(path):
    with zipfile.ZipFile(path) as z:
        core = read_part(z, "docProps/core.xml")
        app = read_part(z, "docProps/app.xml")
    return {
        "creator": _tag(core, "dc:creator"),
        "lastModifiedBy": _tag(core, "cp:lastModifiedBy"),
        "description": _tag(core, "dc:description"),
        "revision": _tag(core, "cp:revision"),
        "created": _parse_time(_tag(core, "dcterms:created")),
        "modified": _parse_time(_tag(core, "dcterms:modified")),
        "application": _tag(app, "Application"),
        "company": _tag(app, "Company"),
        "has_core": core is not None,
        "has_app": app is not None,
    }


def metadata_hits(meta):
    hits = []
    cr = (meta["creator"] or "").strip().lower()
    lm = (meta["lastModifiedBy"] or "").strip().lower()
    if not meta["has_core"]:
        hits.append("no core.xml at all - nothing Office would write")
    if cr in LIB_NAMES:
        hits.append(f"creator '{meta['creator'] or ''}' is a library default, not a person")
    if meta["lastModifiedBy"] is not None and lm in LIB_NAMES and lm != "":
        hits.append(f"lastModifiedBy '{meta['lastModifiedBy']}' is a library default")
    if meta["description"] and re.search(r"generated|python-|openpyxl", meta["description"], re.I):
        hits.append(f"description says '{meta['description']}'")
    app = meta["application"] or ""
    if not meta["has_app"] or not app:
        hits.append("no Application tag - Word, Excel and PowerPoint always write one")
    elif not re.search(r"Microsoft|LibreOffice|Google|Apple|WPS", app) or re.search(r"openpyxl|compatible", app, re.I):
        hits.append(f"Application '{app}' is not an Office app")
    c, m = meta["created"], meta["modified"]
    if c and c.year <= 2014:
        hits.append(f"created {c.date()} is the library template date")
    if c and m and abs((m - c).total_seconds()) < 1 and (meta["revision"] or "1") == "1":
        hits.append("created == modified and revision 1: written once by a program, never opened")
    return hits


# ---- text -----------------------------------------------------------------------------------------------------------
# openpyxl 3.1 writes inline strings (<is><t>) in the sheet part, Excel writes sharedStrings (<si><t>); read both
TEXT_PARTS = {"word": r"word/(document|header\d*|footer\d*|footnotes|endnotes)\.xml$",
              "sheet": r"xl/(sharedStrings|comments\d*|worksheets/sheet\d+)\.xml$",
              "slides": r"ppt/(slides|notesSlides)/[^/]+\.xml$"}
T_NODE = {"word": re.compile(r"(<w:t(?:\s[^>]*)?>)(.*?)(</w:t>)", re.S),
          "sheet": re.compile(r"(<t(?:\s[^>]*)?>)(.*?)(</t>)", re.S),
          "slides": re.compile(r"(<a:t(?:\s[^>]*)?>)(.*?)(</a:t>)", re.S)}
PARA_SPLIT = {"word": re.compile(r"</w:p>"), "sheet": re.compile(r"</si>|</c>"), "slides": re.compile(r"</a:p>")}


def _unescape(s):
    return s.replace("&lt;", "<").replace("&gt;", ">").replace("&quot;", '"').replace("&apos;", "'").replace("&amp;", "&")


def paragraphs(path, kind):
    """Yield (part, index, text) per paragraph (word), shared string (sheet) or text paragraph (slides)."""
    rx_part = re.compile(TEXT_PARTS[kind])
    with zipfile.ZipFile(path) as z:
        for name in z.namelist():
            if not rx_part.search(name):
                continue
            xml = z.read(name).decode("utf-8", errors="replace")
            for i, chunk in enumerate(PARA_SPLIT[kind].split(xml)):
                text = _unescape("".join(m.group(2) for m in T_NODE[kind].finditer(chunk)))
                if text.strip():
                    yield name, i, text


def headings(path):
    """Heading paragraphs of a docx, in order, lower-cased, for the skeleton test."""
    if kind_of(path) != "word":
        return []
    out = []
    with zipfile.ZipFile(path) as z:
        xml = read_part(z, "word/document.xml") or ""
    for chunk in re.split(r"</w:p>", xml):
        if re.search(r'<w:pStyle w:val="(Heading\d|Title|heading\d)"', chunk):
            t = _unescape("".join(m.group(2) for m in T_NODE["word"].finditer(chunk))).strip().lower()
            t = re.sub(r"^\d+[.)]?\s*", "", t)
            if t:
                out.append(t)
    return out


def text_hits(path):
    kind = kind_of(path)
    hits, attrib = [], 0
    for part, i, text in paragraphs(path, kind):
        for tag, rx in TEXT_TELLS:
            if rx.search(text):
                hits.append((tag, part, i, text.strip()[:90]))
        if ATTRIB_RX.search(text) and len(text.split()) >= 4:
            attrib += 1
    if attrib >= 3:
        hits.append(("name-in-parens", "set", attrib, f"{attrib} lines end with a name in parentheses - reads as an attribution ledger"))
    return hits


def set_hits(paths, metas):
    hits = []
    times = sorted((m["created"], p) for p, m in zip(paths, metas) if m["created"])
    if len(times) >= SET_MIN:
        span = (times[-1][0] - times[0][0]).total_seconds()
        if span <= WINDOW_SECONDS:
            hits.append(f"{len(times)} files created inside {int(span)} seconds ({times[0][0]:%Y-%m-%d %H:%M:%S} to "
                        f"{times[-1][0]:%H:%M:%S} UTC) - created in one batch, check the created stamps")
    skel = {}
    for p in paths:
        key = tuple(h for h in headings(p) if any(w in h for w in SKELETON_WORDS))
        if len(key) >= 4:
            skel.setdefault(key, []).append(Path(p).name)
    for key, names in skel.items():
        if len(names) >= SET_MIN:
            hits.append(f"{len(names)} files share one skeleton ({' / '.join(k.title() for k in key)}): " + ", ".join(names))
    return hits


def check(paths):
    metas = [metadata(p) for p in paths]
    total = 0
    for p, m in zip(paths, metas):
        mh = metadata_hits(m)
        th = text_hits(p)
        print(f"{Path(p).name}")
        print(f"  creator={m['creator']!r} lastModifiedBy={m['lastModifiedBy']!r} app={m['application']!r} "
              f"created={m['created']} modified={m['modified']} rev={m['revision']}")
        for h in mh:
            print(f"  [META] {h}")
        for tag, part, i, text in th:
            print(f"  [TEXT] {tag}: {text}")
        if not mh and not th:
            print("  clean")
        total += len(mh) + len(th)
    sh = set_hits(paths, metas) if len(paths) >= SET_MIN else []
    for h in sh:
        print(f"[SET] {h}")
    total += len(sh)
    print(f"{'CLEAN' if total == 0 else str(total) + ' fingerprint hit(s)'}  {len(paths)} file(s)")
    return 0 if total == 0 else 1


# ---- fix ------------------------------------------------------------------------------------------------------------
def _w3c(t):
    return t.astimezone(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _rel(p):
    try:
        return str(p.relative_to(ROOT))
    except ValueError:
        return str(p)


def build_core(author, created, modified, title=""):
    ns = " ".join(f'xmlns:{k}="{v}"' for k, v in CORE_NS.items())
    return ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            f"<cp:coreProperties {ns}>"
            f"<dc:title>{escape(title or '')}</dc:title><dc:subject></dc:subject>"
            f"<dc:creator>{escape(author)}</dc:creator><cp:keywords></cp:keywords><dc:description></dc:description>"
            f"<cp:lastModifiedBy>{escape(author)}</cp:lastModifiedBy><cp:revision>2</cp:revision>"
            f'<dcterms:created xsi:type="dcterms:W3CDTF">{_w3c(created)}</dcterms:created>'
            f'<dcterms:modified xsi:type="dcterms:W3CDTF">{_w3c(modified)}</dcterms:modified>'
            "</cp:coreProperties>")


def build_app(kind, company, old_app_xml):
    """Keep the counts Word would keep; set Application, Company and AppVersion."""
    keep = ""
    for tag in ("Template", "TotalTime", "Pages", "Words", "Characters", "Lines", "Paragraphs", "Slides", "Notes",
                "PresentationFormat", "CharactersWithSpaces", "DocSecurity", "ScaleCrop", "LinksUpToDate",
                "SharedDoc", "HyperlinksChanged"):
        v = _tag(old_app_xml, tag)
        if v is not None:
            keep += f"<{tag}>{escape(v)}</{tag}>"
    if kind == "word" and "<Template>" not in keep:
        keep = "<Template>Normal.dotm</Template>" + keep
    return ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            f'<Properties xmlns="{APP_NS}" xmlns:vt="{VT_NS}">{keep}'
            f"<Application>{APP_NAME[kind]}</Application>"
            f"<Company>{escape(company or '')}</Company><AppVersion>16.0000</AppVersion></Properties>")


def _rules(today):
    """The text rewrites fix is allowed to make on its own, in order. Anything else is reported as LEFT."""
    return [
        (re.compile(r"\b(Checked|Verified|Tested|Reviewed|Built)\s+against\s+(\w[\w ]*?)\s+(release|commit|build|rev(?:ision)?|version|sha)\s+" + HASH, re.I),
         lambda mm: f"{mm.group(1)} against {mm.group(2)} as of {today}"),
        (re.compile(r"\b(release|commit|build|rev(?:ision)?|version|sha)\s+" + HASH, re.I), lambda mm: f"as of {today}"),
        (re.compile(r"\bSOP set build,?\s+phase\s+([A-H])\b"), lambda mm: f"draft {ord(mm.group(1).upper()) - 64}"),
        (re.compile(r"\b(set build|build|pipeline|run|pass),?\s+phase\s+([A-H])\b"), lambda mm: f"draft {ord(mm.group(2).upper()) - 64}"),
        (re.compile(r"\bauto-?generated\b", re.I), lambda mm: "drafted"),
        (re.compile(r"\bgenerated (by|using|with) (python-docx|openpyxl|docx-js|a script|the script|the pipeline|Claude)\b", re.I), lambda mm: "drafted"),
    ]


def rewrite_text(raw, today):
    new = raw
    for rx, fn in _rules(today):
        new = rx.sub(fn, new)
    return new


def rewrite_pairs(raw, today):
    """(old fragment, new fragment) pairs, for a Find/Replace in a live Word doc. Same rules as rewrite_text."""
    pairs, text = [], raw
    for rx, fn in _rules(today):
        for m in rx.finditer(text):
            pairs.append((m.group(0), fn(m)))
        text = rx.sub(fn, text)
    return pairs


def fix_text(xml, kind, today, changes, part):
    """Rewrite the text tells inside one XML part at w:t / t / a:t level. Only whole-node matches are safe."""
    def repl(m):
        open_, body, close = m.groups()
        raw = _unescape(body)
        new = rewrite_text(raw, today)
        if new != raw:
            changes.append((part, raw.strip()[:80], new.strip()[:80]))
            return open_ + escape(new) + close
        return m.group(0)
    return T_NODE[kind].sub(repl, xml)


def fix(paths, author, company, created_at=None, spread_minutes=None, do_text=True):
    if not author or author.strip().lower() in LIB_NAMES:
        print("REFUSED: --author must be a real person's name")
        return 2
    BACKUP.mkdir(parents=True, exist_ok=True)
    today = dt.date.today().strftime("%m/%d/%y")
    now = dt.datetime.now(dt.timezone.utc).replace(microsecond=0)
    bad = 0
    for n, p in enumerate(paths):
        p = Path(p)
        kind = kind_of(p)
        if not kind or not p.is_file():
            print(f"SKIP {p.name}: not a docx/xlsx/pptx on disk")
            bad += 1
            continue
        meta = metadata(p)
        created = meta["created"] or now
        if created_at:
            created = created_at
        if spread_minutes:
            created = created + dt.timedelta(minutes=spread_minutes * n)
        if created.year <= 2014:
            created = now - dt.timedelta(days=1)
        modified = max(now, created + dt.timedelta(minutes=1))
        bk = BACKUP / f"{p.stem}.{dt.datetime.now():%y%m%d-%H%M%S}{p.suffix}"
        shutil.copy2(p, bk)
        tmp = p.with_suffix(p.suffix + ".tmp")
        changes = []
        rx_part = re.compile(TEXT_PARTS[kind])
        with zipfile.ZipFile(p) as zin:
            old_core = read_part(zin, "docProps/core.xml")
            old_app = read_part(zin, "docProps/app.xml")
            title = _tag(old_core, "dc:title") or ""
            names = zin.namelist()
            with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
                for item in zin.infolist():
                    data = zin.read(item.filename)
                    if item.filename == "docProps/core.xml":
                        data = build_core(author, created, modified, title).encode("utf-8")
                    elif item.filename == "docProps/app.xml":
                        data = build_app(kind, company, old_app).encode("utf-8")
                    elif do_text and rx_part.search(item.filename):
                        data = fix_text(data.decode("utf-8"), kind, today, changes, item.filename).encode("utf-8")
                    zout.writestr(item, data)
                if "docProps/core.xml" not in names:
                    zout.writestr("docProps/core.xml", build_core(author, created, modified, title))
                if "docProps/app.xml" not in names:
                    zout.writestr("docProps/app.xml", build_app(kind, company, ""))
        os.replace(tmp, p)
        if "docProps/core.xml" not in names or "docProps/app.xml" not in names:
            _ensure_content_types_and_rels(p, "docProps/core.xml" not in names, "docProps/app.xml" not in names)
        print(f"FIXED {p.name}: author {meta['creator']!r} -> {author!r}; app {meta['application']!r} -> {APP_NAME[kind]!r}; "
              f"created {created:%Y-%m-%d %H:%M}Z modified {modified:%Y-%m-%d %H:%M}Z; backup {_rel(bk)}")
        for part, a, b in changes:
            print(f"   text {Path(part).name}: '{a}' -> '{b}'")
        for t, _, _, txt in text_hits(p):
            print(f"   LEFT {t}: '{txt}' - no safe rewrite, edit by hand")
    return 1 if bad else 0


def _ensure_content_types_and_rels(p, add_core, add_app):
    """A package with no docProps needs the override and the relationship, or Office ignores the new parts."""
    tmp = p.with_suffix(p.suffix + ".tmp")
    with zipfile.ZipFile(p) as zin, zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
        for item in zin.infolist():
            data = zin.read(item.filename)
            if item.filename == "[Content_Types].xml":
                s = data.decode("utf-8")
                if add_core and "core-properties+xml" not in s:
                    s = s.replace("</Types>", '<Override PartName="/docProps/core.xml" ContentType="application/vnd.openxmlformats-package.core-properties+xml"/></Types>')
                if add_app and "extended-properties+xml" not in s:
                    s = s.replace("</Types>", '<Override PartName="/docProps/app.xml" ContentType="application/vnd.openxmlformats-officedocument.extended-properties+xml"/></Types>')
                data = s.encode("utf-8")
            elif item.filename == "_rels/.rels":
                s = data.decode("utf-8")
                if add_core and "core-properties" not in s:
                    s = s.replace("</Relationships>", '<Relationship Id="rIdCoreFp" Type="http://schemas.openxmlformats.org/package/2006/relationships/metadata/core-properties" Target="docProps/core.xml"/></Relationships>')
                if add_app and "extended-properties" not in s:
                    s = s.replace("</Relationships>", '<Relationship Id="rIdAppFp" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/extended-properties" Target="docProps/app.xml"/></Relationships>')
                data = s.encode("utf-8")
            zout.writestr(item, data)
    os.replace(tmp, p)


def stamp_author(path, author, company=""):
    """For generator scripts: call right after save() so the file never leaves with a library stamp."""
    return fix([path], author, company, do_text=False)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="mode", required=True)
    pc = sub.add_parser("check")
    pc.add_argument("files", nargs="+")
    pf = sub.add_parser("fix")
    pf.add_argument("files", nargs="+")
    pf.add_argument("--author", required=True)
    pf.add_argument("--company", default="")
    pf.add_argument("--created", default=None, help='"YYYY-MM-DD HH:MM" local time for the created stamp (default: keep)')
    pf.add_argument("--spread-minutes", type=int, default=None, help="stagger created stamps by N minutes per file in the order given")
    pf.add_argument("--no-text", action="store_true", help="metadata only, leave the text alone")
    a = ap.parse_args(argv)
    missing = [f for f in a.files if not Path(f).is_file()]
    if missing:
        print("REFUSED: not found: " + " | ".join(missing))
        return 2
    unknown = [f for f in a.files if not kind_of(f)]
    if unknown:
        print("REFUSED: not docx/xlsx/pptx: " + " | ".join(unknown))
        return 2
    if a.mode == "check":
        return check(a.files)
    created_at = None
    if a.created:
        created_at = dt.datetime.strptime(a.created, "%Y-%m-%d %H:%M").astimezone()
    return fix(a.files, a.author, a.company, created_at, a.spread_minutes, not a.no_text)


if __name__ == "__main__":
    sys.exit(main())
